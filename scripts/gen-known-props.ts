#!/usr/bin/env bun
// Writes core/sdk/known-props.ts: the props each node type accepts, read from the option types
// at every makeNode and withLongPress call in ui.ts. Run it after adding a component or a prop.
import { readFileSync, writeFileSync } from "fs"
import { join, resolve } from "path"
import ts from "typescript"

const root = resolve(import.meta.dir, "..")
const uiPath = join(root, "core", "sdk", "ui.ts")
const outPath = join(root, "core", "sdk", "known-props.ts")
const CALLS = new Set(["makeNode", "withLongPress"])

// Props that reach a node by a route the call sites do not show.
const EXTRA: Readonly<Record<string, readonly string[]>> = {
  // The component takes `icon` as another name for `name` and passes the options on.
  icon: ["icon"],
  iconButton: ["icon"],
  // withController adds the id of the scroll controller.
  list: ["scrollController"],
  scroll: ["scrollController"],
  virtualRows: ["scrollController"],
}

const literals = (type: ts.Type): string[] => {
  if (type.isUnion()) return type.types.flatMap(literals)

  return type.isStringLiteral() ? [type.value] : []
}

export const collectKnownProps = (): Record<string, string[]> => {
  const config = ts.readConfigFile(join(root, "tsconfig.json"), ts.sys.readFile)
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root)
  const program = ts.createProgram([uiPath], parsed.options)
  const checker = program.getTypeChecker()
  const source = program.getSourceFile(uiPath)!
  const found = new Map<string, Set<string>>()

  const propsOf = (type: ts.Type): string[] | null => {
    if (type.isUnion()) {
      const all = type.types.map(propsOf)

      return all.some((names) => names === null) ? null : all.flatMap((names) => names!)
    }

    if (type.getStringIndexType()) return null

    return checker.getPropertiesOfType(type).map((symbol) => symbol.getName())
  }

  const visit = (node: ts.Node): void => {
    ts.forEachChild(node, visit)

    if (!ts.isCallExpression(node) || !ts.isIdentifier(node.expression)) return
    if (!CALLS.has(node.expression.text) || node.arguments.length < 2) return

    const types = literals(checker.getTypeAtLocation(node.arguments[0]!))
    const names = propsOf(checker.getTypeAtLocation(node.arguments[1]!))

    for (const type of types) {
      const set = found.get(type) ?? new Set<string>()

      found.set(type, set)

      // A type with an open props object is never checked.
      if (names === null) set.add("*")

      for (const name of names ?? []) set.add(name)
    }
  }

  visit(source)

  const out: Record<string, string[]> = {}

  for (const type of [...found.keys()].sort()) {
    const names = [...found.get(type)!, ...(EXTRA[type] ?? [])]

    out[type] = names.includes("*") ? [] : names.sort()
  }

  return out
}

export const renderKnownProps = (table: Record<string, string[]>): string => {
  const lines = Object.entries(table).map(([type, names]) => {
    return names.length === 0 ? `  ${type}: null,` : `  ${type}: ${JSON.stringify(names)},`
  })

  return [
    "// Generated by scripts/gen-known-props.ts from the option types in ui.ts. Do not edit by hand.",
    "export const KNOWN_PROPS: Readonly<Record<string, readonly string[] | null>> = {",
    ...lines,
    "}",
    "",
  ].join("\n")
}

if (import.meta.main) {
  writeFileSync(outPath, renderKnownProps(collectKnownProps()))
  console.log(`wrote ${outPath} (${readFileSync(outPath, "utf8").split("\n").length} lines)`)
}
