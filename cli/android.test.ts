import { describe, expect, test } from "bun:test"
import { createHash } from "crypto"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs"
import { tmpdir } from "os"
import { join } from "path"
import type { AppManifest } from "../core/sdk/manifest.ts"
import {
  androidPackageName,
  androidPermissions,
  androidQtComplete,
  appFiles,
  bundleRuntime,
  clearStaleBuildDir,
  devManifest,
  download,
  installOpenssl,
  OPENSSL_LIBS,
  opensslComplete,
  opensslURL,
  verifyChecksum,
} from "./android.ts"

const manifest: AppManifest = {
  id: "com.example.app",
  name: "example",
  version: "1.2.3",
  targets: ["android"],
  compat: "portable",
}

describe("androidPackageName", () => {
  test("keeps the manifest id for release builds", () => {
    expect(androidPackageName(manifest)).toBe("com.example.app")
  })

  test("appends .dev for dev builds", () => {
    expect(androidPackageName(manifest, true)).toBe("com.example.app.dev")
  })

  test("falls back to the default id", () => {
    expect(androidPackageName(null, true)).toBe("com.pulsar.app.dev")
  })
})

describe("androidPermissions", () => {
  test("maps logical permissions to Android names", () => {
    expect(androidPermissions({ osPermissions: ["camera", "microphone"] })).toEqual([
      "android.permission.CAMERA",
      "android.permission.RECORD_AUDIO",
    ])
  })

  test("expands location, notifications and storage and dedupes", () => {
    const names = androidPermissions({
      osPermissions: ["location", "notifications", "storage", "camera"],
    })

    expect(names).toContain("android.permission.ACCESS_FINE_LOCATION")
    expect(names).toContain("android.permission.POST_NOTIFICATIONS")
    expect(names).toContain("android.permission.READ_MEDIA_IMAGES")
    expect(new Set(names).size).toBe(names.length)
  })

  test("passes unknown entries through verbatim", () => {
    expect(androidPermissions({ osPermissions: ["android.permission.BLUETOOTH"] })).toEqual([
      "android.permission.BLUETOOTH",
    ])
  })

  test("returns an empty list without a manifest", () => {
    expect(androidPermissions(null)).toEqual([])
  })
})

describe("devManifest", () => {
  test("keeps the app fields and changes only the id", () => {
    const dev = devManifest(manifest)

    expect(dev.id).toBe("com.example.app.dev")
    expect(dev.name).toBe("example")
    expect(dev.version).toBe("1.2.3")
    expect(dev.targets).toEqual(["android"])
  })
})

describe("appFiles", () => {
  test("walks the app and skips build, dist and tool directories", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-appfiles-"))

    try {
      writeFileSync(join(dir, "main.ts"), "export {}")
      writeFileSync(join(dir, "pulsar.json"), "{}")
      mkdirSync(join(dir, "ui"))
      writeFileSync(join(dir, "ui", "main.qml"), "Item {}")
      mkdirSync(join(dir, "build"))
      writeFileSync(join(dir, "build", "x"), "x")
      mkdirSync(join(dir, "dist"))
      writeFileSync(join(dir, "dist", "x"), "x")
      mkdirSync(join(dir, "node_modules"))
      writeFileSync(join(dir, "node_modules", "x"), "x")
      mkdirSync(join(dir, ".pulsar"))
      writeFileSync(join(dir, ".pulsar", "dev.json"), "{}")

      expect(appFiles(dir).sort()).toEqual(["main.ts", "pulsar.json", "ui/main.qml"])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe("clearStaleBuildDir", () => {
  test("removes a cache generated by another Pulsar source tree", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-stale-build-"))
    const build = join(dir, "build")

    try {
      mkdirSync(build)
      writeFileSync(join(build, "CMakeCache.txt"), "CMAKE_HOME_DIRECTORY:INTERNAL=/old/pulsar\n")

      expect(clearStaleBuildDir(build, "/new/pulsar")).toBe(true)
      expect(existsSync(build)).toBe(false)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("keeps a cache generated by the same source tree", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-same-build-"))
    const build = join(dir, "build")

    try {
      mkdirSync(build)
      writeFileSync(join(build, "CMakeCache.txt"), `CMAKE_HOME_DIRECTORY:INTERNAL=${dir}\n`)

      expect(clearStaleBuildDir(build, dir)).toBe(false)
      expect(existsSync(join(build, "CMakeCache.txt"))).toBe(true)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("ignores a build directory without a cache", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-empty-build-"))

    try {
      expect(clearStaleBuildDir(dir, "/new/pulsar")).toBe(false)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe("androidQtComplete", () => {
  test("accepts a Qt bundle with multimedia", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-android-qt-"))

    try {
      for (const path of [
        "bin/qt-cmake",
        "qml/QtMultimedia",
        "lib/libQt6Multimedia_arm64-v8a.so",
        "plugins/multimedia",
      ]) {
        mkdirSync(join(dir, path, ".."), { recursive: true })
        writeFileSync(join(dir, path), "")
      }

      expect(androidQtComplete(dir)).toBe(true)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("rejects a bundle from an older release", () => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-old-android-qt-"))

    try {
      mkdirSync(join(dir, "bin"), { recursive: true })
      writeFileSync(join(dir, "bin", "qt-cmake"), "")

      expect(androidQtComplete(dir)).toBe(false)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe("OpenSSL libraries", () => {
  const scratch = (): string => mkdtempSync(join(tmpdir(), "pulsar-openssl-"))
  const sha = (text: string): string => createHash("sha256").update(text).digest("hex")

  test("pins both _3.so libraries with a SHA-256 each", () => {
    expect(OPENSSL_LIBS.map((lib) => lib.name)).toEqual(["libcrypto_3.so", "libssl_3.so"])

    for (const lib of OPENSSL_LIBS) expect(lib.sha256).toMatch(/^[0-9a-f]{64}$/)
  })

  test("downloads from the pinned commit", () => {
    expect(opensslURL("libssl_3.so")).toMatch(
      /^https:\/\/raw\.githubusercontent\.com\/KDAB\/android_openssl\/[0-9a-f]{40}\/ssl_3\/arm64-v8a\/libssl_3\.so$/,
    )
  })

  test("verifyChecksum keeps a matching file", () => {
    const dir = scratch()
    const file = join(dir, "lib.so")

    writeFileSync(file, "good")
    verifyChecksum(file, sha("good"))

    expect(existsSync(file)).toBe(true)
    rmSync(dir, { recursive: true })
  })

  test("verifyChecksum deletes a mismatching file and fails", () => {
    const dir = scratch()
    const file = join(dir, "lib.so")

    writeFileSync(file, "bad")

    expect(() => verifyChecksum(file, sha("good"))).toThrow(/checksum mismatch for lib\.so/)
    expect(existsSync(file)).toBe(false)
    rmSync(dir, { recursive: true })
  })

  test("download retries 5xx answers and then succeeds", async () => {
    const dir = scratch()
    const file = join(dir, "lib.so")

    let calls = 0

    await download("https://example.invalid/lib.so", file, {
      retryDelayMS: 0,
      fetcher: async () => {
        calls += 1

        return calls < 3 ? new Response("", { status: 504 }) : new Response("data")
      },
    })

    expect(calls).toBe(3)
    expect(readFileSync(file, "utf8")).toBe("data")
    rmSync(dir, { recursive: true })
  })

  test("download does not retry a 404", async () => {
    const dir = scratch()

    let calls = 0

    const result = download("https://example.invalid/lib.so", join(dir, "lib.so"), {
      retryDelayMS: 0,
      fetcher: async () => {
        calls += 1

        return new Response("", { status: 404 })
      },
    })

    await expect(result).rejects.toThrow(/404/)
    expect(calls).toBe(1)
    rmSync(dir, { recursive: true })
  })

  test("installOpenssl rejects served bytes that miss the pinned checksum", async () => {
    const dir = scratch()

    const result = installOpenssl(dir, { fetcher: async () => new Response("tampered") })

    await expect(result).rejects.toThrow(/checksum mismatch/)
    expect(opensslComplete(dir)).toBe(false)
    expect(existsSync(join(dir, OPENSSL_LIBS[0].name))).toBe(false)
    rmSync(dir, { recursive: true })
  })
})

describe("bundleRuntime dev flag", () => {
  const bundleText = async (sourcemap: boolean): Promise<string> => {
    const dir = mkdtempSync(join(tmpdir(), "pulsar-devflag-"))

    try {
      writeFileSync(join(dir, "app.ts"), "export {}\n")

      const { result } = bundleRuntime(join(dir, "app.ts"), dir, sourcemap)
      const bundle = await result

      return await bundle.outputs[0]!.text()
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  }

  test("only the dev bundle tells the SDK to warn about unknown props", async () => {
    expect(await bundleText(true)).toContain("__PULSAR_DEV = true")
    expect(await bundleText(false)).not.toContain("__PULSAR_DEV = true")
  })
})
